/**
 * Options for the `msgDlg()` function.
 */
export type MsgDlgOptions = {
    /** A component or function for the title (bar) of the dialog. */
    Title?: StdDlgTitle;
    /**
     * By default the `msgDlg()` function displays only the button `btn_OK`. This can be overridden
     * with the property `Buttons`.
     */
    Buttons?: symbol | symbol[];
    /**
     * The button to be focused when the dialog is shown (the first time). `Focus` can take the
     * following values:
     * - `undefined` (or omitted): The button `btn_OK` or the first button of `Buttons` is focused.
     * - A button (symbol) contained in or equal to `Buttons`: This focuses the corresponding
     *   button.
     * - `null`: Nothing is focused, so the user has to select a button manually.
     */
    Focus?: symbol;
    /**
     * A callback that is executed, if one of the dialog buttons is clicked/pressed.
     * @param btn The button which was clicked/pressed to close the dialog. If the dialog is closed
     * by pressing the `Escape` key, `btn` is the symbol {@link STD_DLG_CANCELLED}.
     * @param dlg The instance of `StdDialog` which is to be closed.
     * @returns `true`, if the dialog can be closed, `false` if the dialog should remain open.
     */
    OnClose?: (btn: symbol, dlg: StdDialog) => Promise<boolean>;
    /** If `true`, the buttons will be laid out vertically (see {@link StdDlgOptions.Vertical}). */
    Vertical?: boolean;
    /** A class name or an array of class names to be set on the dialog. */
    ClassNames?: string | null | undefined | (string | null | undefined)[];
    /**
     * A translation map for the buttons of the dialog. If this is omitted, the current static
     * translation map of `StdDialog` is used (see {@link StdDialog.I18N}).
     */
    I18N?: StdDlgI18N;
};

/**
 * Displays a modal dialog with arbitray content. The dialog shows only the button `btn_OK` by
 * default (see also {@link MsgDlgOptions.Buttons}). The dialog will be disposed of, when the
 * function returns.
 * @param content The content for the message dialog.
 * @param options Options for the message dialog.
 * @returns The button (symbol) which was clicked or the symbol {@link STD_DLG_CANCELLED}, if the
 * dialog was closed by pressing the `Escape` key.
 */
export async function msgDlg(content: StdDlgContent, options?: MsgDlgOptions): Promise<symbol> {
    const stdDlg = new StdDialog({
        /* eslint-disable jsdoc/require-jsdoc */
        Title: options?.Title,
        Content: content,
        Buttons: options?.Buttons ? [options?.Buttons].flat() : [btn_OK],
        Focus: options?.Focus === undefined
            ? [options?.Buttons].flat()[0] ?? btn_OK
            : options?.Focus === null
                ? null
                : options.Focus,
        OnClose: options?.OnClose,
        Vertical: options?.Vertical ?? false,
        ClassNames: ["msg-dlg", options?.ClassNames].flat(),
        I18N: options?.I18N
        /* eslint-enable */
    });
    const btn = await stdDlg.showModal();
    stdDlg.dispose();
    return btn;
}

/**
 * Options for the `confirm()` function.
 */
export type ConfirmOptions = {
    /** A component or function for the title (bar) of the dialog. */
    Title?: StdDlgTitle;
    /**
     * By default the `confirm()` function displays the buttons `btn_YES` and `btn_NO`. This can be
     * overridden with the property `Buttons`.
     */
    Buttons?: symbol | [symbol, symbol];
    /**
     * If the default buttons are overridden with `Buttons`, `confirm()` has no way to decide
     * whether the user has selected the equivalent of 'Yes' or 'No' (as with `btn_YES`), so
     * `ConfirmButton` should be used. `ConfirmButton` must be equal to or contained in `Buttons`.
     * If `ConfirmButton` is omitted, the first entry in `Buttons` (or `Buttons` itself) will be
     * used.
     */
    ConfirmButton?: symbol;
    /**
     * The button to be focused when the dialog is shown (the first time). `Focus` can take the
     * following values:
     * - `undefined` (or omitted): The button `btn_YES` or the first button of `Buttons` is focused.
     * - `btn_YES` or `btn_NO` or a button (symbol) contained in or equal to `Buttons`: This focuses
     *   the corresponding button.
     * - `null`: Nothing is focused, so the user has to select a button manually.
     */
    Focus?: symbol | undefined | null;
    /**
     * A callback that is executed, if one of the dialog buttons is clicked/pressed.
     * @param btn The button which was clicked/pressed to close the dialog. If the dialog is closed
     * by pressing the `Escape` key, `btn` is the symbol {@link STD_DLG_CANCELLED}.
     * @param dlg The instance of `StdDialog` which is to be closed.
     * @returns `true`, if the dialog can be closed, `false` if the dialog should remain open.
     */
    OnClose?: (btn: symbol, dlg: StdDialog) => Promise<boolean>;
    /** If `true`, the buttons will be laid out vertically (see {@link StdDlgOptions.Vertical}). */
    Vertical?: boolean;
    /** A class name or an array of class names to be set on the dialog. */
    ClassNames?: string | null | undefined | (string | null | undefined)[];
    /**
     * A translation map for the buttons of the dialog. If this is omitted, the current static
     * translation map of `StdDialog` is used (see {@link StdDialog.I18N}).
     */
    I18N?: StdDlgI18N;
};

/**
 * Displays a modal dialog in which the user is prompted to select either 'yes' or 'no' for the
 * displayed content. The dialog shows the buttons `btn_YES` and `btn_NO` by default (see also
 * {@link ConfirmOptions.Buttons} and {@link ConfirmOptions.ConfirmButton}). The dialog will be
 * disposed of, when the function returns.
 * @param content The content for the confirm dialog. If this is a string which is an empty string
 * or a string that only contains whitespace, a `Text` component with that string will be used
 * (which almost never has a visual representation).
 * @param options Options for the confirm dialog.
 * @returns `true` only if the button `btn_YES` was clicked/pressed, otherwise `false`.
 */
export async function confirm(content: StdDlgContent, options?: ConfirmOptions): Promise<boolean> {
    const confirmButton = options?.ConfirmButton ?? ([options?.Buttons].flat())[0] ?? btn_YES;
    const stdDlg = new StdDialog({
        /* eslint-disable jsdoc/require-jsdoc */
        Title: options?.Title,
        Content: content,
        Buttons: options?.Buttons ? [options.Buttons].flat() : [btn_YES, btn_NO],
        Focus: options?.Focus === undefined
            ? [options?.Buttons].flat()[0] ?? btn_YES
            : options?.Focus === null
                ? null
                : options.Focus,
        OnClose: options?.OnClose,
        Vertical: options?.Vertical ?? false,
        ClassNames: ["confirm", options?.ClassNames].flat(),
        I18N: options?.I18N
        /* eslint-enable */
    });
    const btn = await stdDlg.showModal();
    stdDlg.dispose();
    return btn === confirmButton;
}

/**
 * Options for the `queryInput()` function.
 */
export type QueryInputOptions = {
    /** A component or function for the title (bar) of the dialog. */
    Title?: StdDlgTitle;
    /**
     * An input component that is derived from the `Input`, `LabeledInputComponent`, `Select`,
     * `TextArea`, `RadioButtonGroup` or `LabeledRadioButtonGroup` component found in
     * `@vanilla-ts/dom`/`@vanilla-ts/components`. This gives a lot of flexibility for creating
     * input dialogs for various data types. If `Input` is omitted, an instance of `TextInput` from
     * `@vanilla-ts/dom` with no further configuration is used.
     */
    Input?: Input | LabeledInputComponent<Input> | Select | TextArea | RadioButtonGroup | LabeledRadioButtonGroup;
    /** The content to be displayed _after_ the input component. */
    AfterInput?: StdDlgContent;
    /**
     * By default the `queryInput()` function displays the buttons `btn_OK` and `btn_CANCEL`. This
     * can be overridden with the property `Buttons`.
     */
    Buttons?: symbol | symbol[];
    /**
     * If the default buttons are overridden with `Buttons`, `queryInput()` has no way to decide
     * whether the user has selected the equivalent of 'Yes' or 'No' (as with `btn_OK`), so
     * `ConfirmButton` should be used. `ConfirmButton` must be equal to or contained in `Buttons`.
     * If `ConfirmButton` is omitted, the first entry in `Buttons` (or `Buttons` itself) will be
     * used.
     */
    ConfirmButton?: symbol;
    /**
     * A callback that is executed, if one of the dialog buttons is clicked/pressed.
     * @param btn The button which was clicked/pressed to close the dialog. If the dialog is closed
     * by pressing the `Escape` key, `btn` is the symbol {@link STD_DLG_CANCELLED}.
     * @param dlg The instance of `StdDialog` which is to be closed.
     * @returns `true`, if the dialog can be closed, `false` if the dialog should remain open.
     */
    OnClose?: (btn: symbol, dlg: StdDialog) => Promise<boolean>;
    /**
     * If available, this function will be called, if the `ConfirmButton` is clicked/pressed. If the
     * function returns `true`, the dialog is closed, otherwise the dialog stays open.
     * @param value The `Value` property of the input component. This is always of type `string`,
     * except for inputs of type `Checkbox` or `LabeledCheckbox` where `value` is of type `boolean`.
     * @returns `true`, if the validation is successful, otherwise `false`.
     */
    Validate?: (value: string | boolean) => Promise<boolean>;
    /** If `true`, the buttons will be laid out vertically (see {@link StdDlgOptions.Vertical}). */
    Vertical?: boolean;
    /** A class name or an array of class names to be set on the dialog. */
    ClassNames?: string | null | undefined | (string | null | undefined)[];
    /**
     * A translation map for the buttons of the dialog. If this is omitted, the current static
     * translation map of `StdDialog` is used (see {@link StdDialog.I18N}).
     */
    I18N?: StdDlgI18N;
};

/**
 * Displays a modal dialog in which the user can enter a value in an input component. The dialog
 * shows the buttons `btn_OK` and `btn_CANCEL` by default (see also
 * {@link QueryInputOptions.Buttons} and {@link QueryInputOptions.ConfirmButton}). Pressing the
 * 'Enter' key while the input component has the focus is equivalent to clicking on the button
 * `btn_OK` (or the button denoted by `ConfirmButton`). The only exception is if `input` is an
 * instance of `TextArea`, in this case pressing `Enter` does not close the dialog, instead the
 * `Enter` key is handled by the `TextArea` component itself. The dialog will be disposed of, when
 * the function returns.
 * @param content The content for the query input dialog. This content is displayed _before_ the
 * input component. If this is a string which is an empty string or a string that only contains
 * whitespace, a `Text` component with that string will be used (which almost never has a visual
 * representation).
 * @param options Options for the query input dialog.
 * @returns An object with three properties:
 * - `OK`: `true` only if the button `btn_OK` (or the `ConfirmButton`) was clicked/pressed or the
 *   'Enter' key was pressed while the input component had the focus, otherwise `false`.
 * - `Value`: The value of the input component. If `Input` is an instance of `Checkbox` or
 *   `LabeledCheckbox` then `Value` reflects the `Checked` state of `Input` (`true` or `false`).
 * - `Button`: The button (symbol) which was clicked or the symbol {@link STD_DLG_CANCELLED}, if the
 *   dialog was closed by pressing the `Escape` key.
 */
export async function queryInput(content: StdDlgContent | null | undefined, options?: QueryInputOptions): Promise<{ OK: boolean; Value: string | boolean; Button: symbol, }> { // eslint-disable-line jsdoc/require-jsdoc
    const input = options?.Input
        ? options.Input
        : new TextInput;
    const stdDlg = new StdDialog({
        /* eslint-disable jsdoc/require-jsdoc */
        Title: options?.Title,
        Content: content ?? [],
        Buttons: options?.Buttons ? [options.Buttons].flat() : [btn_OK, btn_CANCEL],
        Focus: input,
        OnClose: options?.OnClose,
        Vertical: options?.Vertical ?? false,
        ClassNames: ["query-input", "query-" + toKebapCase(input.ClassName), options?.ClassNames].flat(),
        I18N: options?.I18N
        /* eslint-enable */
    });
    stdDlg.Dialog.insert(
        stdDlg.Dialog.Children.length - 1,
        input,
        ...[
            typeof options?.AfterInput === "function"
                ? options.AfterInput(stdDlg)
                : options?.AfterInput
        ]
            .flat()
            .filter(e => e !== undefined && e !== null)
            .map(e => typeof e === "string" ? new Text(e) : e)
    );
    const confirmButton = options?.ConfirmButton ?? ([options?.Buttons].flat())[0] ?? btn_OK;
    (input instanceof TextArea) || (<IElementComponent<HTMLElement>>input).on("keydown", async (ev: KeyboardEvent) => {
        if (ev.key === "Enter") {
            ev.preventDefault();
            ev.stopImmediatePropagation();
            if (!options?.Validate || await options.Validate((input instanceof Checkbox || input instanceof LabeledCheckbox) ? input.Checked : input.Value)) {
                stdDlg.Dialog.close(confirmButton.description);
            }
        }
    });
    stdDlg.Dialog.on("dlg-close", async (ev: DialogCloseEvent) => {
        // Only, if the confirm button was clicked/pressed! Otherwise the validation would be
        // executed for _every_ button and also the dialog couldn't be canceled!
        if (ev.$.ReturnValue === confirmButton.description) {
            ev.preventDefault();
            ev.stopImmediatePropagation();
            if (!options?.Validate || await options.Validate((input instanceof Checkbox || input instanceof LabeledCheckbox) ? input.Checked : input.Value)) {
                // `forceClose()` !!! Otherwise this would cause and endless `dlg-close` event loop!
                stdDlg.Dialog.forceClose(confirmButton.description);
            }
        }
    });
    const btn = await stdDlg.showModal();
    const result = {
        /* eslint-disable jsdoc/require-jsdoc */
        OK: btn === confirmButton,
        Value: (input instanceof Checkbox || input instanceof LabeledCheckbox) ? input.Checked : input.Value,
        Button: btn
        /* eslint-enable */
    };
    stdDlg.dispose();
    return result;
}
